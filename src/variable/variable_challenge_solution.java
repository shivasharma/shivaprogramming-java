package variable;
/*
Create 3 variables:
Student name
Student age
Student GPA
Store values inside them
Print the values in a complete sentence

expected output: Student John is 20 years old and has a GPA of 3.5
 */
public  class variable_challenge_solution {


    void main() {

        String name = "John";
        int age = 20;
        double gpa = 3.5;

        System.out.println("Student " + name + " is " + age +
                " years old and has a GPA of " + gpa);
    }

}




